function extractYouTubeId(urlOrId) {
  if (!urlOrId || typeof urlOrId !== "string") return null;
  const trimmed = urlOrId.trim();

  // If already standard 11-char ID
  if (/^[a-zA-Z0-9_-]{11}$/.test(trimmed)) {
    return trimmed;
  }

  try {
    const parsed = new URL(trimmed);
    const host = parsed.hostname.toLowerCase();
    const isYouTube = host === "youtube.com" || host === "www.youtube.com" || host === "m.youtube.com";
    const isShortLink = host === "youtu.be" || host === "www.youtu.be";

    // youtu.be/<id>
    if (isShortLink) {
      const id = parsed.pathname.slice(1).split("/")[0].split("?")[0];
      return /^[a-zA-Z0-9_-]{11}$/.test(id) ? id : null;
    }

    // youtube.com/...
    if (isYouTube) {
      if (parsed.searchParams.has("v")) {
        const v = parsed.searchParams.get("v");
        return /^[a-zA-Z0-9_-]{11}$/.test(v) ? v : null;
      }
      if (parsed.pathname.startsWith("/embed/")) {
        const id = parsed.pathname.split("/embed/")[1]?.split("/")[0]?.split("?")[0];
        return /^[a-zA-Z0-9_-]{11}$/.test(id) ? id : null;
      }
      if (parsed.pathname.startsWith("/shorts/")) {
        const id = parsed.pathname.split("/shorts/")[1]?.split("/")[0]?.split("?")[0];
        return /^[a-zA-Z0-9_-]{11}$/.test(id) ? id : null;
      }
    }

    // Explicitly reject non-YouTube hosts
    return null;
  } catch {
    // Regex fallback only matching strict https?://(?:www\.)?youtube\.com or youtu\.be
    const match = trimmed.match(/^(?:https?:\/\/)?(?:www\.|m\.)?(?:youtu\.be\/|youtube\.com\/(?:watch\?v=|embed\/|shorts\/))([a-zA-Z0-9_-]{11})/i);
    if (match && match[1]) {
      return match[1];
    }
  }

  return null;
}

function filterVideos(filters = {}) {
  const {
    educationLevel,
    grade,
    classGrade,
    board,
    stream,
    branch,
    scheme,
    semester,
    subject,
    topic,
    language,
    verificationStatus,
    q,
    limit = 24,
    page = 1,
  } = filters;

  const normLevel = educationLevel ? educationLevel.toLowerCase().trim() : null;
  const normGrade = (classGrade || grade || "").toString().toLowerCase().trim();
  const normBoard = board ? board.toLowerCase().trim() : null;
  const normStream = stream ? stream.toLowerCase().trim() : null;
  const normBranch = branch ? branch.toLowerCase().trim() : null;
  const normScheme = scheme ? scheme.toLowerCase().trim() : null;
  const normSemester = semester ? semester.toString().toLowerCase().trim() : null;
  const normSubject = subject ? subject.toLowerCase().trim() : null;
  const normTopic = topic ? topic.toLowerCase().trim() : null;
  const normLanguage = language ? language.toLowerCase().trim() : null;
  const normVerification = verificationStatus ? verificationStatus.toLowerCase().trim() : null;
  const query = q ? q.toLowerCase().trim() : null;

  let results = CURATED_VIDEOS.map((v) => {
    // Derive educationLevel if not explicitly present
    let derivedLevel = v.educationLevel;
    if (!derivedLevel) {
      const cls = Number(v.classGrade);
      if (cls >= 1 && cls <= 5) derivedLevel = "primary";
      else if (cls >= 6 && cls <= 8) derivedLevel = "middle";
      else if (cls >= 9 && cls <= 10) derivedLevel = "secondary";
      else if (cls >= 11 && cls <= 12) derivedLevel = "higher_secondary";
      else if (v.branch || v.semester) derivedLevel = "diploma";
      else derivedLevel = "secondary";
    }

    return {
      ...v,
      educationLevel: derivedLevel,
      verificationStatus: v.verificationStatus || "verified",
      isVerified: (v.verificationStatus || "verified") === "verified",
    };
  });

  // 1. Education Level
  if (normLevel && normLevel !== "all") {
    results = results.filter((v) => v.educationLevel === normLevel);
  }

  // 2. Class / Grade
  if (normGrade && normGrade !== "all") {
    results = results.filter((v) => {
      if (v.classGrade && v.classGrade.toLowerCase() === normGrade) return true;
      if (v.grade && v.grade.toLowerCase().includes(normGrade)) return true;
      return false;
    });
  }

  // 3. Board
  if (normBoard && normBoard !== "all") {
    results = results.filter((v) => {
      if (!v.board || v.board.toLowerCase() === "all" || v.board.toLowerCase() === "general") return true; // generic curriculum compatible with all boards
      const b = v.board.toLowerCase();
      return b === normBoard || b.split(",").map((s) => s.trim()).includes(normBoard);
    });
  }

  // 4. Stream (Higher Secondary)
  if (normStream && normStream !== "all") {
    results = results.filter((v) => {
      if (!v.stream) return true;
      return v.stream.toLowerCase() === normStream;
    });
  }

  // 5. Branch (Diploma)
  if (normBranch && normBranch !== "all") {
    results = results.filter((v) => {
      if (!v.branch) return false;
      return v.branch.toLowerCase() === normBranch || normBranch === "all";
    });
  }

  // 6. Scheme (Diploma)
  if (normScheme && normScheme !== "all") {
    results = results.filter((v) => {
      if (!v.scheme || v.scheme.toLowerCase() === "all" || v.scheme.toLowerCase() === "general") return true;
      return v.scheme.toLowerCase() === normScheme;
    });
  }

  // 7. Semester (Diploma)
  if (normSemester && normSemester !== "all") {
    const semNum = Number(normSemester);
    results = results.filter((v) => {
      if (v.semester === undefined || v.semester === null) return true;
      return String(v.semester) === normSemester || v.semester === semNum;
    });
  }

  // 8. Subject
  if (normSubject && normSubject !== "all") {
    results = results.filter((v) => {
      const subj = (v.subject || v.topic || "").toLowerCase();
      return subj.includes(normSubject);
    });
  }

  // 9. Topic / Chapter
  if (normTopic && normTopic !== "all") {
    results = results.filter((v) => {
      const top = (v.chapter || v.topic || "").toLowerCase();
      return top.includes(normTopic);
    });
  }

  // 10. Language
  if (normLanguage && normLanguage !== "all") {
    results = results.filter((v) => v.language.toLowerCase() === normLanguage);
  }

  // 11. Verification Status
  if (normVerification && normVerification !== "all") {
    results = results.filter((v) => v.verificationStatus.toLowerCase() === normVerification);
  }

  // 12. Search Query
  if (query) {
    results = results.filter((v) => {
      return (
        (v.title && v.title.toLowerCase().includes(query)) ||
        (v.description && v.description.toLowerCase().includes(query)) ||
        (v.channel && v.channel.toLowerCase().includes(query)) ||
        (v.topic && v.topic.toLowerCase().includes(query)) ||
        (v.subject && v.subject.toLowerCase().includes(query)) ||
        (v.chapter && v.chapter.toLowerCase().includes(query)) ||
        (v.branch && v.branch.toLowerCase().includes(query))
      );
    });
  }

  const total = results.length;
  const numLimit = Math.min(Math.max(Number(limit) || 24, 1), 100);
  const numPage = Math.max(Number(page) || 1, 1);
  const startIdx = (numPage - 1) * numLimit;
  const paginated = results.slice(startIdx, startIdx + numLimit);

  return {
    total,
    page: numPage,
    totalPages: Math.ceil(total / numLimit) || 1,
    videos: paginated,
  };
}

